"""Regenerate owned, synthetic Python archive/schema compatibility fixtures.

No production database, hardware, credentials, or runtime dependency is used.
"""
from pathlib import Path
import hashlib
import io
import json
import sqlite3
import sys
import tempfile
import wave

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from radioinspector.contracts import MonitoringSession, Sweep, ReceiverObservation
from radioinspector.session_store import SQLiteSessionStore
from radioinspector.monitoring.store import ProjectStore

HERE = Path(__file__).resolve().parent
DATA = HERE / 'fixtures'
STAMP = '2026-11-11T12:00:00.123456Z'


def main():
    DATA.mkdir(exist_ok=True)
    fixture = json.loads((ROOT/'contracts/fixtures/measurement-v1.json').read_text())
    session = MonitoringSession.from_dict(dict(fixture['session'], created_at=STAMP))
    with tempfile.TemporaryDirectory() as directory:
        source = Path(directory)/'canonical.sqlite'
        db = SQLiteSessionStore(str(source))
        statements = [row[0] for row in db._connection.execute("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid")]
        ddl = []
        for statement in statements:
            if statement.startswith('CREATE TABLE '):
                statement = statement.replace('CREATE TABLE ', 'CREATE TABLE IF NOT EXISTS ', 1)
            elif statement.startswith('CREATE UNIQUE INDEX '):
                statement = statement.replace('CREATE UNIQUE INDEX ', 'CREATE UNIQUE INDEX IF NOT EXISTS ', 1)
            elif statement.startswith('CREATE INDEX '):
                statement = statement.replace('CREATE INDEX ', 'CREATE INDEX IF NOT EXISTS ', 1)
            ddl.append(statement+';')
        (HERE.parent/'src/schema_v6.sql').write_text('-- Canonical fixed DDL from Python SQLiteSessionStore, generated by tests/generate_fixtures.py.\n'+'\n\n'.join(ddl)+'\n')
        db.close()
        target = DATA/'legacy_v5_utf16.sqlite'
        target.unlink(missing_ok=True)
        with sqlite3.connect(target) as raw:
            raw.execute("PRAGMA encoding='UTF-16'")
            raw.execute("CREATE TABLE synthetic_encoding_marker(value TEXT)")
            raw.execute("INSERT INTO synthetic_encoding_marker VALUES ('owned synthetic UTF-16 fixture')")
        db = SQLiteSessionStore(str(target))
        db.save_session(session)
        for index, identifier in enumerate(('arrival-last', 'tie-\ue000', 'tie-\U00010000', 'arrival-first')):
            value = dict(fixture['sweep'], id=identifier)
            db.record_sweep(Sweep.from_dict(value))
        db.record_observation(ReceiverObservation.from_dict(fixture['observation']))
        records = ProjectStore(db)
        records.put('project', dict(id='synthetic-project', created_at=STAMP, session_ids=[session.id],
                    state='armed', autostart=True, resume_requested=True, webhook_enabled=True))
        records.put('baseline', dict(id='synthetic-baseline', project_id='synthetic-project', created_at=STAMP, source_refs=[dict(session_id=session.id,stream_id=session.streams[0].id,sweep_id='arrival-last')]))
        records.put('event', dict(id='synthetic-event',project_id='synthetic-project',created_at=STAMP,state='open',source_refs=[dict(session_id=session.id,stream_id=session.streams[0].id,sweep_id='arrival-last')]))
        output=io.BytesIO()
        with wave.open(output,'wb') as audio:
            audio.setnchannels(1);audio.setsampwidth(2);audio.setframerate(8000);audio.writeframes(b'\x01\x00\xff\x7f'*8)
        payload=output.getvalue()
        db.save_instrument_artifact(dict(id='synthetic-audio',session_id=session.id,stream_id=session.streams[1].id,
            schema_version=1,kind='audio',mime_type='audio/wav',filename='synthetic.wav',sha256=hashlib.sha256(payload).hexdigest(),created_at=STAMP,payload=payload,metadata={'occurred_at':STAMP,'synthetic':True}))
        with db._connection:
            db._connection.execute("INSERT INTO monitoring_webhooks VALUES (?,?,?)",('synthetic-project','https://example.invalid/owned-fixture','synthetic-fixture-secret'))
            db._connection.execute("INSERT INTO monitoring_notifications VALUES (?,?,?,?,?,?,?,?,?,?)",('synthetic-notification','synthetic-project',STAMP,'{"synthetic":true}','pending',2,STAMP,'synthetic retry',STAMP,None))
            db._connection.execute('DROP TABLE sweep_ingestion')
            db._connection.execute('PRAGMA user_version=5')
            # Legacy offset text is intentionally preserved, not rewritten on open.
            db._connection.execute("UPDATE sweeps SET started_at='2026-11-11T15:00:00.123456+03:00' WHERE id='arrival-last'")
        db._connection.execute('PRAGMA wal_checkpoint(TRUNCATE)')
        db._connection.execute('PRAGMA journal_mode=DELETE')
        tables = ('sessions','streams','sweeps','observations','monitoring_records','monitoring_webhooks','monitoring_notifications','monitoring_sessions','monitoring_sweep_index','instrument_artifacts')
        snapshot = {}
        for table in tables:
            rows = db._connection.execute('SELECT * FROM '+table+' ORDER BY rowid').fetchall()
            snapshot[table] = [[{'bytes_hex':value.hex()} if isinstance(value,bytes) else value for value in row] for row in rows]
        (DATA/'legacy_v5_utf16.snapshot.json').write_text(json.dumps(snapshot,ensure_ascii=False,allow_nan=False,indent=2)+'\n')
        db.close()
    (DATA/'README.md').write_text('Owned synthetic compatibility fixture. Generated with tests/generate_fixtures.py from foundations 96696a0. Schema v5, monitoring4, UTF-16, original offset time text, JSON -0 and one closed WAV. No real measurements or credentials.\n')


if __name__ == '__main__':
    main()
