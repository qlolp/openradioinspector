#!/usr/bin/env python3
"""Deterministic OpenAPI 3.1 model generator (Python stdlib + pinned rustfmt) (generator format 1).

The authoritative input is radioinspector.web.openapi.document(). --schema-source
accepts that Python module in another checkout, or a captured OpenAPI JSON file.
--check computes all outputs in memory and never rewrites stale files.
"""
from __future__ import annotations
import argparse
import hashlib
import importlib.util
import json
import os
import shutil
import subprocess
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
TEMPLATES = Path(__file__).resolve().parent / "runtime"
HEADER = "Generated by tools/contracts/generate.py; do not edit."
RUSTFMT_VERSION = "rustfmt 1.10.0-stable (58cf8f9c35 2026-10-13)"


def load_document(source: Path | None):
    source = source or ROOT / "radioinspector/web/openapi.py"
    if source.suffix == ".json":
        return json.loads(source.read_text(encoding="utf-8"))
    sys.path.insert(0, str(source.resolve().parents[2]))
    spec = importlib.util.spec_from_file_location("radioinspector.web.openapi", source)
    if spec is None or spec.loader is None:
        raise ValueError(f"Cannot load schema module: {source}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.document()


def ref_name(schema):
    return schema.get("$ref", "").rsplit("/", 1)[-1]


def kind(schema):
    value = schema.get("type")
    return next((v for v in value if v != "null"), "null") if isinstance(value, list) else value


def nullable(schema):
    return isinstance(schema.get('type'), list) and 'null' in schema['type']


def enum_name(model, field):
    return {("DeviceStream", "role"): "DeviceRole", ("Candidate", "state"): "CandidateState"}.get((model, field), model + "".join(p.title() for p in field.split("_")))


def enums(schemas):
    return {(enum_name(name, key)): prop["enum"] for name, schema in schemas.items()
            for key, prop in schema.get("properties", {}).items() if "enum" in prop}


def rust_type(schema, model="", field=""):
    if "$ref" in schema:
        return ref_name(schema)
    if "enum" in schema:
        return enum_name(model, field)
    if kind(schema) == "array": return "Vec<" + rust_type(schema.get("items", {})) + ">"
    return {"string": "UtcTimestamp" if schema.get("format") == "date-time" else "String",
            "integer": "i64" if isinstance(schema.get("type"), list) else "u64",
            "number": "f64", "boolean": "bool", "object": "JSONObject"}.get(kind(schema), "serde_json::Value")


def rust_models(schemas):
    lines = ["// " + HEADER, "use serde::{Deserialize, Serialize};", "use crate::UtcTimestamp;", "pub type JSONObject = std::collections::BTreeMap<String, serde_json::Value>;", ""]
    for name, values in enums(schemas).items():
        lines += ["#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]", f"pub enum {name} {{"]
        for value in values:
            lines += [f'    #[serde(rename = "{value}")]', "    " + "".join(p.title() for p in value.split("_")) + ","]
        lines += ["}", f"impl crate::RestoreKeys for {name} {{ fn restore_keys(&mut self) {{}} }}", ""]
    for name, schema in schemas.items():
        if name == "JSONObject": continue
        lines += ["#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]", f"pub struct {name}" + ("<T = serde_json::Value>" if name == "Envelope" else "") + " {"]
        for field, prop in schema["properties"].items():
            required = field in schema.get("required", [])
            ty = "T" if name == "Envelope" and field == "data" else "PlatformError" if name == "ErrorEnvelope" and field == "error" else rust_type(prop, name, field)
            if not required or nullable(prop):
                ty = f"Option<{ty}>"
            if not required:
                lines += ['    #[serde(default, skip_serializing_if = "Option::is_none")]']
            elif nullable(prop):
                lines += ['    #[serde(deserialize_with = "crate::codec::deserialize_required_nullable")]']
            if field == "contract": lines += ['    #[serde(deserialize_with = "crate::codec::deserialize_contract")]']
            if field == "contract_version": lines += ['    #[serde(deserialize_with = "crate::codec::deserialize_contract_version")]' if required else '    #[serde(deserialize_with = "crate::codec::deserialize_optional_contract_version")]']
            lines += [f"    pub {field}: {ty},"]
        lines += ['    #[serde(default, flatten)]', "    pub extra: JSONObject,", "}", ""]
        generic = "<T: crate::RestoreKeys>" if name == "Envelope" else ""
        target = name + ("<T>" if name == "Envelope" else "")
        lines += [f"impl{generic} crate::RestoreKeys for {target} {{", "    fn restore_keys(&mut self) {", "        crate::RestoreKeys::restore_keys(&mut self.extra);"]
        for field, prop in schema["properties"].items():
            # Scalars have no map keys; only nested models/open JSON need a walk.
            if field == "data" and name == "Envelope" or "$ref" in prop or kind(prop) == "object" or kind(prop) == "array" and ("$ref" in prop.get("items", {}) or kind(prop.get("items", {})) == "object"):
                lines += [f"        crate::RestoreKeys::restore_keys(&mut self.{field});"]
        lines += ["    }", "}", ""]
    lines += ["#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]", "pub struct PlatformError {", "    pub code: String,", "    pub message: String,", '    #[serde(default, flatten)]', "    pub extra: JSONObject,", "}", "", "impl crate::RestoreKeys for PlatformError { fn restore_keys(&mut self) { crate::RestoreKeys::restore_keys(&mut self.extra); } }", "", "impl<T> Envelope<T> {", "    pub fn new(data: T) -> Self {", '        Self { contract: crate::CONTRACT_NAME.into(), contract_version: crate::CONTRACT_VERSION, data, extra: JSONObject::new() }', "    }", "}", ""]
    return "\n".join(lines)


def ts_type(schema, model="", field=""):
    if "$ref" in schema: return ref_name(schema)
    if "enum" in schema: return enum_name(model, field)
    if kind(schema) == "array": return f"Array<{ts_type(schema.get('items', {}))}>"
    return {"string": "string", "integer": "Integer", "number": "number", "boolean": "boolean", "object": "JSONObject"}.get(kind(schema), "JSONValue") + (" | null" if isinstance(schema.get("type"), list) and "null" in schema["type"] else "")


def ts_models(schemas):
    lines = ["// " + HEADER, "import type {JSONValue, JSONObject, Integer} from './codec.ts';", "export type {JSONValue, JSONObject, Integer} from './codec.ts';", ""]
    for name, values in enums(schemas).items():
        lines += [f"export type {name} = " + " | ".join(json.dumps(v) for v in values) + ";"]
    for name, schema in schemas.items():
        if name == "JSONObject": continue
        lines += [f"export interface {name}" + ("<T = JSONValue>" if name == "Envelope" else "") + " {"]
        for field, prop in schema["properties"].items():
            ty = "T" if name == "Envelope" and field == "data" else "PlatformError" if name == "ErrorEnvelope" and field == "error" else ts_type(prop, name, field)
            if "const" in prop: ty = json.dumps(prop["const"])
            lines += [f"  {field}{'' if field in schema.get('required', []) else '?'}: {ty};"]
        lines += ["  [key: string]: unknown;", "}", ""]
    lines += ["export interface PlatformError {code: string; message: string; [key: string]: unknown;}"]
    return "\n".join(lines) + "\n"


def swift_type(schema, model="", field=""):
    if "$ref" in schema: return ref_name(schema)
    if "enum" in schema: return enum_name(model, field)
    if kind(schema) == "array": return "[" + swift_type(schema.get("items", {})) + "]"
    return {"string": "UtcTimestamp" if schema.get("format") == "date-time" else "String", "integer": "Int64" if isinstance(schema.get("type"), list) else "UInt64", "number": "Double", "boolean": "Bool", "object": "JSONObject"}.get(kind(schema), "JSONValue")


def swift_read(prop, expr, model="", field=""):
    if "$ref" in prop: return f"try {ref_name(prop)}(json: {expr})"
    if "enum" in prop: return f"try {enum_name(model, field)}(json: {expr})"
    if kind(prop) == "array": return f"try {expr}.requireArray().map {{ {swift_read(prop['items'], '$0')} }}"
    ty = swift_type(prop, model, field)
    return f"try {ty}(json: {expr})" if ty == "UtcTimestamp" else f"try {expr}.require{ {'String':'String','UInt64':'UInt64','Int64':'Int64','Double':'Double','Bool':'Bool','JSONObject':'Object'}.get(ty, 'Value')}()" if ty != "JSONValue" else expr


def swift_write(prop, expr, model="", field=""):
    if "$ref" in prop or "enum" in prop or swift_type(prop, model, field) == "UtcTimestamp": return f"{expr}.json"
    if kind(prop) == "array": return f".array({expr}.map {{ {swift_write(prop['items'], '$0')} }})"
    return {"string": f".string({expr})", "integer": f".integer(String({expr}))", "number": f".number({expr})", "boolean": f".bool({expr})", "object": f".object({expr})"}.get(kind(prop), expr)


def swift_models(schemas):
    lines = ["// " + HEADER, "import Foundation", ""]
    for name, values in enums(schemas).items():
        lines += [f"public enum {name}: String, Sendable, Codable, CaseIterable {{"]
        for value in values: lines += [f'    case {value} = "{value}"']
        lines += ["    public init(json: JSONValue) throws {", '        guard let value = Self(rawValue: try json.requireString()) else { throw ContractError.invalid("Unknown enum value") }', "        self = value", "    }", "    public var json: JSONValue { .string(rawValue) }", "}", ""]
    for name, schema in {**schemas, "PlatformError": {"properties": {"code": {"type": "string"}, "message": {"type": "string"}}, "required": ["code", "message"]}}.items():
        if name == "JSONObject": continue
        lines += [f"public struct {name}: ContractModel, Equatable, Sendable {{"]
        for field, prop in schema["properties"].items():
            ty = "PlatformError" if name == "ErrorEnvelope" and field == "error" else swift_type(prop, name, field)
            optional = field not in schema.get("required", []) or nullable(prop)
            lines += [f"    public var {field}: {ty}{'?' if optional else ''}"]
        parameters = []
        for field, prop in schema["properties"].items():
            ty = "PlatformError" if name == "ErrorEnvelope" and field == "error" else swift_type(prop, name, field)
            optional = field not in schema.get("required", []) or nullable(prop)
            parameters.append(f"{field}: {ty}" + ("? = nil" if optional else ""))
        parameters.append("extra: JSONObject = [:]")
        lines += ["    public var extra: JSONObject", "    public init(" + ", ".join(parameters) + ") {"]
        lines += [f"        self.{field} = {field}" for field in schema["properties"]]
        lines += ["        self.extra = extra", "    }", "    public init(json: JSONValue) throws {", "        var object = try json.requireObject()"]
        for field, prop in schema["properties"].items():
            required = field in schema.get("required", [])
            expr = "value"
            value = f"try PlatformError(json: {expr})" if name == "ErrorEnvelope" and field == "error" else swift_read(prop, expr, name, field)
            if required:
                decoded = value.replace('value', field+'Value')
                if nullable(prop):
                    decoded = f'{field}Value == .null ? nil : {decoded}'
                lines += [f'        guard let {field}Value = object.removeValue(forKey: "{field}") else {{ throw ContractError.invalid("Missing {field}") }}', f"        {field} = {decoded}"]
            else:
                lines += [f'        if let value = object.removeValue(forKey: "{field}"), value != .null {{ {field} = {value} }} else {{ {field} = nil }}']
            if "const" in prop:
                condition = json.dumps(prop["const"], ensure_ascii=False)
                lines += [f'        guard {field} == {condition}{" || " + field + " == nil" if not required else ""} else {{ throw ContractError.invalid("Unsupported {field}") }}']
        lines += ["        extra = object", "    }", "    public var json: JSONValue {", "        var object = extra"]
        for field, prop in schema["properties"].items():
            expr = "value" if field not in schema.get("required", []) or nullable(prop) else field
            value = f"{expr}.json" if name == "ErrorEnvelope" and field == "error" else swift_write(prop, expr, name, field)
            if field in schema.get("required", []) and nullable(prop):
                lines += [f'        if let value = {field} {{ object["{field}"] = {value} }} else {{ object["{field}"] = .null }}']
            elif field in schema.get("required", []): lines += [f'        object["{field}"] = {value}']
            else: lines += [f'        if let value = {field} {{ object["{field}"] = {value} }}']
        lines += ["        return .object(object)", "    }", "}", ""]
    return "\n".join(lines)


def format_rust(source):
    executable = os.environ.get("RUSTFMT") or shutil.which("rustfmt")
    if executable is None:
        candidate = Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo")) / "bin/rustfmt"
        executable = str(candidate)
    version = subprocess.run([executable, "--version"], capture_output=True, text=True, check=False)
    if version.returncode or version.stdout.strip() != RUSTFMT_VERSION:
        raise ValueError("Use rustfmt from Rust 1.99.1; set RUSTFMT to its executable")
    result = subprocess.run([executable, "--config-path", str(Path(__file__).with_name("rustfmt.toml"))], input=source, capture_output=True, text=True, check=False)
    if result.returncode:
        raise ValueError("rustfmt failed: " + result.stderr.strip())
    return result.stdout


def render(document):
    document = json.loads(json.dumps(document, sort_keys=True))
    if document.get("openapi") != "3.1.0": raise ValueError("Expected authoritative OpenAPI 3.1.0 document")
    schemas = document["components"]["schemas"]
    canonical = json.dumps(document, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    operations = {op["operationId"]: {"method": method.upper(), "path": path, "query": [p["name"] for p in op.get("parameters", []) if p["in"] == "query"], "max_request_bytes": op.get("x-ori-max-request-bytes")}
                  for path, methods in document["paths"].items() for method, op in methods.items()}
    ts_decoders = "\n".join(f"export const decode{name} = (value: JSONValue): {name} => decodeModel('{name}', value) as unknown as {name};\nexport const encode{name} = (value: {name}): string => encodeModel('{name}', value);" for name in schemas if name != "JSONObject")
    rust_operations = ["// " + HEADER, "#[derive(Debug, Clone, Copy)]", "pub struct Operation { pub operation_id: &'static str, pub method: &'static str, pub path: &'static str, pub query: &'static [&'static str], pub max_request_bytes: Option<usize> }", "pub const OPERATIONS: &[Operation] = &["]
    swift_operations = ["// " + HEADER, "public struct OperationDescriptor: Sendable { public let method: String; public let path: String; public let query: [String]; public let maxRequestBytes: Int? }", "public let operations: [String: OperationDescriptor] = ["]
    for name, op in operations.items():
        values = [json.dumps(op["method"]), json.dumps(op["path"]), json.dumps(op["query"])]
        budget = op["max_request_bytes"]
        rust_operations += [f"    Operation {{ operation_id: {json.dumps(name)}, method: {values[0]}, path: {values[1]}, query: &{values[2]}, max_request_bytes: {'None' if budget is None else f'Some({budget})'} }},"]
        swift_operations += [f"    {json.dumps(name)}: OperationDescriptor(method: {values[0]}, path: {values[1]}, query: {values[2]}, maxRequestBytes: {'nil' if budget is None else budget}),"]
    rust_operations += ["];", ""]
    swift_operations += ["]", ""]
    outputs = {
        "contracts/generated/openapi-v1.json": canonical,
        "contracts/generated/manifest.json": json.dumps({"generator_format": 1, "schema_sha256": hashlib.sha256(canonical.encode()).hexdigest(), "toolchains": {"rust": "1.99.1", "rustfmt": RUSTFMT_VERSION, "python": "3.15.1", "typescript": "7.0.2", "node": "26.13.0", "swift": "6.4.2"}}, sort_keys=True, indent=2) + "\n",
        "crates/ori-contracts/src/models.rs": format_rust(rust_models(schemas)),
        "crates/ori-contracts/src/operations.rs": format_rust("\n".join(rust_operations)),
        "contracts/generated/swift/Sources/ORIContracts/Operations.swift": "\n".join(swift_operations),
        "contracts/generated/typescript/.gitignore": "node_modules/\n",
        "contracts/generated/typescript/models.ts": ts_models(schemas),
        "contracts/generated/typescript/schema.ts": "// " + HEADER + "\nexport const schemas = " + json.dumps(schemas, ensure_ascii=False, sort_keys=True, indent=2) + " as const;\nexport const operations = " + json.dumps(operations, ensure_ascii=False, sort_keys=True, indent=2) + " as const;\n",
        "contracts/generated/typescript/index.ts": "// " + HEADER + "\nexport * from './models.ts';\nexport * from './codec.ts';\nexport {operations} from './schema.ts';\nimport type {JSONValue} from './codec.ts';\nimport {decodeModel, encodeModel} from './codec.ts';\nimport type {" + ", ".join(n for n in schemas if n != 'JSONObject') + "} from './models.ts';\n" + ts_decoders + "\n",
        "contracts/generated/typescript/package.json": json.dumps({"name": "@openradioinspector/contracts", "version": "1.0.0", "private": True, "type": "module", "exports": "./index.ts", "devDependencies": {"typescript": "7.0.2"}, "scripts": {"check": "tsc -p tsconfig.json"}}, indent=2) + "\n",
        "contracts/generated/typescript/tsconfig.json": json.dumps({"compilerOptions": {"target": "ES2024", "module": "NodeNext", "moduleResolution": "NodeNext", "strict": True, "noEmit": True, "allowImportingTsExtensions": True, "skipLibCheck": False, "lib": ["ES2024", "DOM"]}, "include": ["*.ts"]}, indent=2) + "\n",
        "contracts/generated/swift/Package.swift": '// swift-tools-version: 6.4\n// ' + HEADER + '\nimport PackageDescription\nlet package = Package(name: "ORIContracts", platforms: [.macOS(.v14)], products: [.library(name: "ORIContracts", targets: ["ORIContracts"])], targets: [.target(name: "ORIContracts")])\n',
        "contracts/generated/swift/Sources/ORIContracts/Models.swift": swift_models(schemas),
    }
    for name, target in [("typescript.ts", "contracts/generated/typescript/codec.ts"), ("swift.swift", "contracts/generated/swift/Sources/ORIContracts/Codec.swift")]:
        outputs[target] = "// " + HEADER + "\n" + (TEMPLATES / name).read_text(encoding="utf-8")
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema-source", type=Path)
    parser.add_argument("--output-root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        outputs = render(load_document(args.schema_source))
    except (OSError, ValueError, ImportError) as error:
        print(f"contract generation failed: {error}", file=sys.stderr)
        return 2
    stale = []
    for name, content in outputs.items():
        path = args.output_root / name
        if args.check:
            if not path.is_file() or path.read_bytes() != content.encode("utf-8"): stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode("utf-8"))
    if stale:
        print("Stale contract outputs:\n" + "\n".join(stale), file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs)} contract outputs")
    return 0


if __name__ == "__main__": raise SystemExit(main())
